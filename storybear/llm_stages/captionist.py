"""
stages.py
=========
Pipeline stages 3-9.

Each class is independently instantiable and testable.
They share no global state — data flows through method arguments and return values.

LLM calls
---------
Every class that uses an LLM exposes a `_call_llm(prompt: str) -> str` helper
that you replace with your actual API call (OpenAI, Anthropic, etc.).
A system prompt class variable (`SYSTEM_PROMPT`) is also provided for easy
customisation without subclassing.

Stage map
---------
3. Captionist   — PlotRecord  → CaptionedRecord   (LLM)
4. Foodie       — CaptionedRecord → RankedRecord  (LLM, vision)
5. Secretary    — list[RankedRecord] → list[RankedRecord]  (top-N selector)
-- 6. Editor       — list[RankedRecord] → ReportMeta (LLM)
-- 7. Junior       — list[RankedRecord] + ReportMeta → list[OrderedRecord]  (LLM)
-- 8. Artist       — list[OrderedRecord] → list[FinalRecord] (LLM, vision, in-place edit)
-- 9. Typography   — list[FinalRecord] + ReportMeta → Path (.docx)
"""

